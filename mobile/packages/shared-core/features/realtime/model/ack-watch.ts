/**
 * Следит, отвечает ли сервер на отправки по сокету.
 *
 * `socket.connected` — это мнение клиента. Когда приложение свёрнуто, Android замораживает
 * таймеры JS и рвёт TCP, а Socket.IO узнаёт об обрыве только по своему пингу — то есть по
 * таймеру, который стоит. Сокет остаётся «подключённым», `emit` уходит в никуда, и
 * вызывающий код считает точку доставленной. Подтверждение сервера — единственный честный
 * признак, что канал жив.
 *
 * Таймеров здесь нет намеренно: время передаёт вызывающий код, и проверка работает там же,
 * где таймеры стоят, — в фоновой задаче геолокации.
 */
export interface AckWatch {
  /**
   * Отмечает отправку. `false` — прошлые отправки ждут ответа дольше порога: каналу
   * верить нельзя, сообщение стоит продублировать другим путём.
   */
  sent(nowMs: number): boolean;
  /** Сервер ответил — канал жив. */
  acked(): void;
  /** Соединение пересоздано — прошлые ожидания больше ничего не значат. */
  reset(): void;
}

export function createAckWatch(staleAfterMs: number): AckWatch {
  /** Момент первой отправки, на которую ещё не было ни одного ответа. */
  let waitingSince: number | null = null;

  return {
    acked() {
      waitingSince = null;
    },
    reset() {
      waitingSince = null;
    },
    sent(nowMs) {
      if (waitingSince == null) {
        waitingSince = nowMs;
        return true;
      }
      return nowMs - waitingSince <= staleAfterMs;
    },
  };
}
